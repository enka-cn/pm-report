-- 003_handoff_acceptance.sql
--
-- 交接的「真空期」。
--
-- 003 之前，交接是瞬间生效的：改完 owner 它立刻从我的驾驶舱消失。
-- 但对看护型责任来说这很危险 —— 对方可能压根还没接，
-- 于是这条责任在**谁的视图里都不存在了**。而它的触发条件可能一年后才成立，
-- 到那时没人记得还有这回事。
--
-- 这是看护型项目最阴的失效方式：不是忘了做，而是责任在交接的缝隙里蒸发。
--
-- 补法不是加一个「已交接」状态（那是从 owner 派生的结论，两个来源描述同一件事
-- 迟早漂移，正是 D2 反对的），而是**加一个事实**：
--   pending = owner <> 'me' AND handoff_accepted_at IS NULL
-- 待接收期间它仍然留在我的看护清单里，标注「已交出，等 XX 接收」—— 我还在兜底。
ALTER TABLE project ADD COLUMN handoff_accepted_at TEXT;
